#!/bin/bash
# Regenerates k8s/keycloak-realm.yml from keycloak/realm-export.json, the single source of the realm.
# Run it after every change to the realm file, then commit both files.
set -euo pipefail
cd "$(dirname "$0")/.."

{
  echo "# GENERATED by k8s/sync-realm.sh from keycloak/realm-export.json - do not edit by hand."
  kubectl create configmap keycloak-realm \
    --namespace pokemon-drafter \
    --from-file=realm-export.json=keycloak/realm-export.json \
    --dry-run=client -o yaml
} > k8s/keycloak-realm.yml

echo "k8s/keycloak-realm.yml regenerated"
